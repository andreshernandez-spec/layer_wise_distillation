"""Emit the paper's tables as markdown, generated from the run records.

An audit found 119 numeric literals in the paper and only 23 bound to claims.py; most
of the rest were table cells. A table nobody regenerates is a table that drifts. Each
block below is delimited so check_paper.py can assert the paper contains it verbatim.

    python experiments/paper/tables.py            # print every table
    python experiments/paper/tables.py --name heal
"""
import argparse
import glob
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from claims import P1, P2, P2S, load                 # noqa: E402

BUDGETS = [1e5, 1e6, 3e6, 1e7]


def _runs():
    """Every heal run from both pods, grouped by arm and budget."""
    d = {}
    for src, pod in ((P2, "pod1"), (P2S, "pod2")):
        for r in load(f"{src}/heal_*.json"):
            r["_pod"] = pod
            arm = r["init"] + r.get("tag", "").replace("_control", "")
            d.setdefault((arm, r["tokens"]), []).append(r)
    return d


def _matched(runs, arm, tok):
    return sorted(r["loss_after"] for r in runs.get((arm, tok), []) if r.get("warmup") == 500)


def _heals():
    """Seed-0, pod-1 record per cell, for the curve that was published first."""
    d = {}
    for r in load(f"{P2}/heal_*.json"):
        if r.get("tag", ""):
            continue
        if r.get("heal_seed", r["seed"]) != r["seed"]:
            continue
        d[(r["init"], r["tokens"])] = r
    return d


def t_interface():
    rows = [("L (live real)", "L_iid_q1e08_s0", "1e7", "0"),
            ("R (anchors, recycled)", "R_iid_q1e08_s0", "0.95e6", "0"),
            ("C_mix (recipe)", "C_mix_q1e08_s0", "0.95e6", "9.1e7"),
            ("G_iid (pure noise)", "G_iid_q1e08_s0", "0", "1e8")]
    out = ["| arm | distinct real positions | noise positions | eps | stitching delta |",
           "|---|---|---|---|---|"]
    for label, stem, real, noise in rows:
        r = json.load(open(f"{P1}/{stem}.json"))
        out.append(f"| {label} | {real} | {noise} | {r['final_eval']:.3f} | "
                   f"{r['stitch']['delta']:.3f} |")
    return "\n".join(out)


def t_heal():
    H = _heals()
    out = ["| heal tokens | random init | stagewise (noise recipe) | oracle (real activations) |",
           "|---|---|---|---|"]
    out.append(f"| 0 | {H[('random', 1e5)]['loss_before']:.4f} | "
               f"{H[('stagewise', 1e5)]['loss_before']:.4f} | "
               f"{H[('oracle', 1e5)]['loss_before']:.4f} |")
    for t in BUDGETS:
        c = [f"{H[(k, t)]['loss_after']:.4f}" if (k, t) in H else "-"
             for k in ("random", "stagewise", "oracle")]
        out.append(f"| {t:.0e} | " + " | ".join(c) + " |")
    return "\n".join(out)


def t_equalflops():
    R = _runs()
    rnd = _matched(R, "random_eqflops", 183670000.0)
    orc = _matched(R, "oracle", 1e7)
    sw = _matched(R, "stagewise", 1e7)
    dg = _matched(R, "stagewise_dagger", 1e7)
    m = lambda v: float(np.mean(v))
    def cell(v):
        return (f"**{m(v):.4f}**" + (f" (n={len(v)}, spread {np.ptp(v):.4f})"
                                     if len(v) > 1 else " (n=1)"))
    out = ["| arm | heal tokens | held-out loss | gap to random |", "|---|---|---|---|",
           f"| random init | **1.8367e8** | {cell(rnd)} | |",
           f"| oracle, real activations | 1e7 | {cell(orc)} | **{m(rnd) - m(orc):+.3f}** |",
           f"| noise recipe | 1e7 | {cell(sw)} | **{m(rnd) - m(sw):+.3f}** |",
           f"| noise recipe + on-policy retraining | 1e7 | {cell(dg)} | **{m(rnd) - m(dg):+.3f}** |"]
    return "\n".join(out)


def t_drift():
    d = json.load(open(f"{P2}/drift_C.json"))
    real, pred = d["realized_drift"][1:], d["predicted_from_stage1_drift"]
    n = len(real)
    out = ["| interface | " + " | ".join(str(i + 1) for i in range(n)) + " |",
           "|---" * (n + 1) + "|",
           "| realized drift (noise recipe) | " +
           " | ".join(f"{x:.3f}" if i < n - 1 else f"**{x:.3f}**" for i, x in enumerate(real)) + " |",
           "| pure propagation, no fresh error | " +
           " | ".join(f"{x:.3f}" if i < n - 1 else f"**{x:.3f}**" for i, x in enumerate(pred)) + " |"]
    return "\n".join(out)


TABLES = {"interface": t_interface, "heal": t_heal, "equalflops": t_equalflops, "drift": t_drift}


def main(a):
    for name, fn in TABLES.items():
        if a.name and a.name != name:
            continue
        print(f"<!-- TABLE:{name} generated by experiments/paper/tables.py -->")
        print(fn())
        print(f"<!-- /TABLE:{name} -->\n")


if __name__ == "__main__":
    p = argparse.ArgumentParser(); p.add_argument("--name", default=None)
    main(p.parse_args())
